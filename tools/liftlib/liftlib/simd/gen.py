"""gen.py — .ll の `__asm_*` 宣言から C helper を生成する (CAB-54)。

  - 名前非依存: `__asm_<base>[__N|.N]` の接尾番号は無視し, (base mnemonic, 戻り型, 引数型) だけで意味を決める
  - 正規名: `__asm_<base>__<ret><args>` (例 __asm_mulss__xxd) へ IR をリネームすれば, 複数バイナリの
    helper を 1 本の C に統合できる (`canonicalize`)
  - 未被覆の mnemonic (テーブルに無い形) は一覧化し, 任意で fail-fast stub を出す
  - i256 (ymm): wasm32 ABI = 引数 u64×4 に平坦化 / 戻り値 sret (C の struct Y 返し) (LIFTLIB #241)
"""
import re
import sys
from collections import OrderedDict

from . import kernels

TAG = {"i128": "x", "i64": "q", "i32": "d", "i16": "w", "i8": "b", "i256": "y", "void": "v"}
CT = {"x": "u128", "q": "u64", "d": "u32", "w": "u16", "b": "u8", "v": "void", "y": "Y"}

DECL_RE = re.compile(r"(?m)^declare[ \t]+(\S+)[ \t]+@(__asm_[\w.\-]+)\(([^)\n]*)\)(?:[ \t]+\S+)*[ \t]*$")
SUFFIX_RE = re.compile(r"(?:__\d+|\.\d+)$")
CANON_RE = re.compile(r"__[xqdwbyv]{1,6}$")


class Decl:
    def __init__(self, name, ret, args):
        self.name = name                      # '__asm_mulss__2'
        self.ret = TAG.get(ret, "?")
        self.args = [TAG.get(a, "?") for a in args]
        self.base = base_of(name)
        self.rawret, self.rawargs = ret, args

    @property
    def canon(self):
        return ("__asm_%s__%s%s" % (self.base, self.ret, "".join(self.args))).replace("?", "p")

    @property
    def sig(self):
        return "%s(%s)" % (self.ret, ",".join(self.args))


def base_of(name):
    n = name[len("__asm_"):]
    m = CANON_RE.search(n)
    if m and n[:m.start()]:
        n = n[:m.start()]
    return SUFFIX_RE.sub("", n)


def scan_decls(text):
    out = OrderedDict()
    for m in DECL_RE.finditer(text):
        ret, name, args = m.group(1), m.group(2), m.group(3)
        at = []
        for a in args.split(","):
            a = a.strip()
            if a:
                at.append(a.split()[0])
        out[name] = Decl(name, ret, at)
    return list(out.values())


def canonicalize(text):
    """IR 内の `__asm_*` を正規名へリネーム (declare は重複除去)。返値 (text, rename_map)"""
    decls = scan_decls(text)
    mp = {d.name: d.canon for d in decls}
    if not mp:
        return text, mp

    def rep(m):
        return "@" + mp.get(m.group(1), m.group(1))
    text = re.sub(r"@(__asm_[\w.\-]+)", rep, text)
    seen, out = set(), []
    for ln in text.split("\n"):
        m = re.match(r"^declare\s+\S+\s+@(__asm_[\w.\-]+)\(", ln)
        if m:
            if m.group(1) in seen:
                continue
            seen.add(m.group(1))
        out.append(ln)
    return "\n".join(out), mp


def emit_c(decls, use_names="orig", stub_unsupported=True, extra_header=""):
    """C ソースを生成。返値 (c_text, report)。use_names: 'orig' (IR の宣言名) | 'canon'"""
    lines = ['/* generated by liftlib simd gen — 宣言シグネチャ駆動 (名前接尾非依存) */',
             '#include "liftlib_simd.h"', extra_header, ""]
    rep = dict(generated=[], unsupported=[], approx=[], dup=[])
    seen = set()
    uses_pcmp = False
    for d in decls:
        nm = d.name if use_names == "orig" else d.canon
        if nm in seen:
            rep["dup"].append(nm)
            continue
        seen.add(nm)
        if "?" in d.ret or "?" in "".join(d.args):
            rep["unsupported"].append((d.name, d.sig, "未知の型タグ (i16 等) は ABI 未定義"))
            if stub_unsupported:
                lines.append(_stub(nm, d, "unknown type"))
            continue
        sp = kernels.lookup(d.base, d.ret, d.args)
        if sp is None:
            rep["unsupported"].append((d.name, d.sig, "mnemonic/形が kernels に無い"))
            if stub_unsupported:
                lines.append(_stub(nm, d, "unimplemented"))
            continue
        params, pro = _params(d)
        rt = CT[d.ret]
        lines.append("/* %s%s */" % (d.base, (" — " + sp.note) if sp.note else ""))
        body = sp.body
        if sp.lanes is not None:
            inner, iargs = sp.lanes
            ip = ", ".join("%s p%d" % (CT[t], i) for i, t in enumerate(iargs))
            lines.append("static inline u128 %s__l(%s) { %s }" % (nm, ip, inner.body))
            lo = ", ".join(("YLO(p%d)" if t == "y" else "p%d") % i for i, t in enumerate(d.args))
            hi = ", ".join(("YHI(p%d)" if t == "y" else "p%d") % i for i, t in enumerate(d.args))
            body = "return MKY(%s__l(%s), %s__l(%s));" % (nm, lo, nm, hi)
        lines.append("LL_EXPORT %s %s(%s) { %s%s }" % (rt, nm, params, pro, body))
        rep["generated"].append((nm, d.sig))
        if d.base.endswith("pcmpistri") and d.ret == "v":
            uses_pcmp = True
        if not sp.exact:
            rep["approx"].append(nm)
    if uses_pcmp:
        lines.append("LL_EXPORT u32 ll_pcmpistr_ecx; LL_EXPORT u32 ll_pcmpistr_fl;")
    return "\n".join(lines) + "\n", rep


def _params(d):
    """(C 引数リスト, 関数先頭 prologue)。i256 (y) は wasm32 ABI に合わせ u64×4 に平坦化し prologue で Y に束ねる。"""
    ps, pro = [], ""
    for i, t in enumerate(d.args):
        if t == "y":
            ps += ["u64 p%d_%d" % (i, k) for k in range(4)]
            pro += "Y p%d = {{p%d_0, p%d_1, p%d_2, p%d_3}}; " % ((i,) * 5)
        else:
            ps.append("%s p%d" % (CT.get(t, "u128"), i))
    return ", ".join(ps) or "void", pro


def _stub(nm, d, why):
    params, _ = _params(d) if "?" not in "".join(d.args) else (", ".join("u128 p%d" % i for i in range(len(d.args))) or "void", "")
    rt = CT.get(d.ret, "u128")
    ret = "" if rt == "void" else ("Y z = {{0, 0, 0, 0}}; return z;" if rt == "Y" else "return 0;")
    return ("LL_EXPORT %s %s(%s) { __builtin_trap(); %s } /* %s */"
            % (rt, nm, params, ret, why))


# ---------------------------------------------------------------------------------
# mnemonic 単位の被覆判定 (census 用)
# ---------------------------------------------------------------------------------
_REP_SIGS = [("x", ["x"]), ("x", ["x", "x"]), ("x", ["x", "d"]), ("x", ["x", "q"]), ("x", ["d"]), ("x", ["q"]),
             ("x", ["x", "b"]), ("x", ["x", "x", "b"]), ("x", ["x", "x", "x"]), ("x", ["x", "x", "d"]),
             ("x", ["x", "x", "q"]), ("d", ["x"]), ("q", ["x"]), ("d", ["d"]), ("d", ["q"]), ("v", ["x", "x"]),
             ("v", ["x", "q"]), ("v", ["x", "d"]), ("x", []), ("q", []), ("v", ["b"]),
             ("v", ["x", "x", "b"]), ("d", ["x", "x", "b"])]
# ymm (i256) 形の代表署名 (LIFTLIB #241)。VEX-256 mnemonic のみ試す
_YREP_SIGS = [("y", ["y"]), ("y", ["y", "y"]), ("y", ["y", "b"]), ("y", ["y", "y", "b"]), ("y", ["y", "y", "y"]),
              ("y", ["y", "x", "b"]), ("x", ["y", "b"]), ("v", ["y", "y"])]


def mnemonic_covered(base):
    for r, a in _REP_SIGS + _YREP_SIGS:
        if kernels.lookup(base, r, a) is not None:
            return True
    return False


def coverage(mnemonics):
    cov = [m for m in mnemonics if mnemonic_covered(m)]
    cs = set(cov)
    return cov, [m for m in mnemonics if m not in cs]


def main(argv):
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("ll", nargs="+")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--canon", default="", help="正規名化した .ll の出力先 (入力 1 本のとき)")
    ap.add_argument("--names", default="orig", choices=["orig", "canon"])
    a = ap.parse_args(argv)
    decls = []
    for p in a.ll:
        decls += scan_decls(open(p).read())
    if a.canon:
        t, mp = canonicalize(open(a.ll[0]).read())
        open(a.canon, "w").write(t)
        decls = scan_decls(t)
        a.names = "canon"
    c, rep = emit_c(decls, use_names=a.names)
    open(a.out, "w").write(c)
    print("[simd.gen] generated %d, unsupported %d, approx %d" % (len(rep["generated"]), len(rep["unsupported"]), len(rep["approx"])))
    for u in rep["unsupported"]:
        print("  UNSUPPORTED", u)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
