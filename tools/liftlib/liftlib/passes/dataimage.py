"""dataimage.py — PE の .rdata/.data を wasm 線形メモリの固定アドレスに敷設する C を生成する (tools/m6/m6_data_gen.py の統合版)。

 - on-disk の 8B ポインタ (ImageBase 基準) は .reloc (DIR64) を基準に新ベースへ補正する
 - 補正要否の判定は「元値が PE image 範囲内か」(`img.base <= v < img.base + SizeOfImage`) で行う
   (lowbase x64c/lb_data_gen.py 同規約。LB_BASE<0x400000 でも補正漏れ 0 — CAB-220)
 - 生成物: `m6_data_install()` を 1 度呼ぶと VA_BASE+RVA に .rdata/.data が敷設される
   (lift IR の VA 直値 → VA_BASE 系 remap (remap.shift_va) と対で使う)
"""
import struct
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from liftlib.pe import Image


def sections_raw(img: "Image") -> list[tuple[str, int, bytes]]:
    """ottlib.Bin 互換: (name, rva, bytes[vsize]) の列。"""
    out: list[tuple[str, int, bytes]] = []
    for s in img.pe.sections:
        sva, vsz, roff, rsz = s.VirtualAddress, s.Misc_VirtualSize, s.PointerToRawData, s.SizeOfRawData
        nm = s.Name.rstrip(b"\0").decode("utf-8", "replace")
        if vsz == 0 or sva == 0:
            continue
        raw = img.raw[roff:roff + min(rsz, vsz)] if rsz else b""
        raw = raw + bytes(max(0, vsz - len(raw)))
        out.append((nm, sva, raw))
    return out


def gen_data_c(img: "Image", va_base: int = 0x30000000, img_base: int | None = None,
               names: tuple[str, ...] = (".rdata", ".data"), header: bool = True) -> tuple[str, dict[str, int]]:
    img_base = img.base if img_base is None else img_base
    secs_all = sections_raw(img)
    secs = [(n, lo, bytearray(d)) for (n, lo, d) in secs_all if n in names]
    relocs = img.relocs_dir64()
    counts: dict[str, int] = {}
    for (n, lo, sd) in secs:
        c = 0
        for r in relocs:
            if lo <= r <= lo + len(sd) - 8:  # #593: セクション末尾の 8B slot も対象 (旧 `<` は off-by-one, m11 #572 と同根)
                off = r - lo
                v = struct.unpack_from("<Q", sd, off)[0]
                nt = v - img_base + va_base
                # 判定は「元値側の image 範囲」で行う (lowbase x64c/lb_data_gen.py と同じ規約)。
                # 旧実装の `0x400000 <= nt < 0x180000000` は補正後ポインタの妥当域判定で,
                # LB_BASE < 0x400000 (lowbase, CAB-90/CAB-220) のとき image 内ポインタ
                # (nt = LB_BASE+RVA < 0x400000) が大量に存在するにもかかわらず
                # DIR64 補正が黙って落ちていた (CAB-90 検収で実機確認)。
                if img_base <= v < img_base + img.size:
                    sd[off:off + 8] = struct.pack("<Q", nt)
                    c += 1
        counts[n] = c
    parts = []
    if header:
        parts.append("/* auto-generated by liftlib dataimage: PE の %s を VA_BASE=0x%x + RVA に敷設する。\n"
                     " * 8B ポインタは .reloc (DIR64) 基準で新ベースに補正済み。m6_data_install() を lift 関数呼出前に 1 度だけ呼ぶ。 */\n"
                     % (",".join(names), va_base))
    parts.append("#include <stdint.h>\n#include <stddef.h>\n#include <string.h>\n")
    for (n, lo, sd) in secs:
        sym = n.replace(".", "_")
        parts.append("static const unsigned char dlld_%s[] = {\n" % sym)
        rows = [",".join("0x%02x" % b for b in sd[i:i + 16]) for i in range(0, len(sd), 16)]
        parts.append(",\n".join(rows))
        parts.append("\n};\n")
        parts.append("#define %s_LO 0x%xu\n" % (sym.upper(), va_base + lo))
        parts.append("#define %s_LEN %du\n" % (sym.upper(), len(sd)))
    parts.append("\nvoid m6_data_install(void) {\n")
    for (n, lo, sd) in secs:
        sym = n.replace(".", "_")
        parts.append("  memcpy((void*)0x%xu, dlld_%s, %du);\n" % (va_base + lo, sym, len(sd)))
    parts.append("}\n")
    return "".join(parts), counts
