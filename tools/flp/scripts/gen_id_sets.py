#!/usr/bin/env python3
"""Generate src/id_sets.ts: (a) event ids known to upstream PyFLP 2.2.1 (ids only, reference), (b) ids written by FLEngine (corpus/engine_event_ids.json).
Usage: work/venv/bin/python scripts/gen_id_sets.py   (needs pyflp in the venv built by flp_e2e.sh)"""
import inspect, json
import pyflp
from pyflp._events import EventEnum
import pyflp.project, pyflp.channel, pyflp.mixer, pyflp.pattern, pyflp.plugin, pyflp.arrangement, pyflp.controller, pyflp.timemarker

ids = set()
for mod in [pyflp.project, pyflp.channel, pyflp.mixer, pyflp.pattern, pyflp.plugin, pyflp.arrangement, pyflp.controller, pyflp.timemarker]:
    for _, c in inspect.getmembers(mod, inspect.isclass):
        if issubclass(c, EventEnum) and c is not EventEnum and c.__module__ == mod.__name__:
            for m in c:
                ids.add(int(m.value))
eng = sorted(int(k) for k in json.load(open('corpus/engine_event_ids.json'))['ids'])
def arr(xs): return '[' + ', '.join(str(x) for x in xs) + ']'
open('src/id_sets.ts', 'w').write(f"""// GENERATED by scripts/gen_id_sets.py -- do not edit.
/** event ids that upstream PyFLP {getattr(pyflp, '__version__', '2.2.1')} models (ids only; used to flag what is NOT publicly documented) */
export const UPSTREAM_IDS: ReadonlySet<number> = new Set({arr(sorted(ids))});
/** event ids that FLEngine_x64.dll (FL 26.1.7) writes via direct call sites of its stream helpers (engine_event_ids.json) */
export const ENGINE_WRITTEN_IDS: ReadonlySet<number> = new Set({arr(eng)});
""")
print(len(ids), len(eng))
