#!/usr/bin/env python3
"""FLEngine のローダ表 420 名 (work/flengine_ipp_names.json) から wasm 用 ipp_lookup 表を生成する。
   実装済み (src/ipp_min.h 宣言) は本物、それ以外は呼ばれたら名前を記録して trap する fail-fast stub。
   → shim の GetProcAddress("dsp_ippv2", name) は ipp_lookup(name) の関数表 index を返せばよい。"""
import json, re, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
names = [n for n in json.load(open(f'{HERE}/work/flengine_ipp_names.json'))['x86_64'] if n.startswith('ipp')]
sys.path.insert(0, HERE)
from common import implemented_names
impl = implemented_names()
missing_impl = sorted(impl - set(names))
out = ['/* generated by tools/ipp/gen_table.py — 編集禁止 */', '#include "../ipp_min.h"', 'static const char *g_last;',
       'const char *ipp_unimpl_name(void) { return g_last; }',
       '#define STUB(n) static int stub_##n(void) { g_last = #n; __builtin_trap(); return -1; }']
stubs = [n for n in names if n not in impl]
for n in stubs: out.append(f'STUB({n})')
out += ['typedef struct { const char *name; void *fn; int impl; } IppEntry;', 'static const IppEntry T[] = {']
for n in sorted(names):
    out.append(f'  {{"{n}", (void *)' + (n if n in impl else f'stub_{n}') + f', {1 if n in impl else 0}}},')
out += ['};', 'int ipp_table_count(void) { return (int)(sizeof T / sizeof *T); }',
        'const char *ipp_table_name(int i) { return T[i].name; }', 'void *ipp_table_fn(int i) { return T[i].fn; }', 'int ipp_table_impl(int i) { return T[i].impl; }',
        '#include <string.h>', 'void *ipp_lookup(const char *name) { int lo = 0, hi = (int)(sizeof T / sizeof *T) - 1;',
        '  while (lo <= hi) { int m = (lo + hi) / 2, c = strcmp(name, T[m].name); if (!c) return T[m].fn; if (c < 0) hi = m - 1; else lo = m + 1; }', '  return 0; }',
        '/* fail-fast 検証用: 名前で引いた関数を引数なしで呼ぶ (stub なら trap し ipp_unimpl_name() に名前が残る) */',
        'int ipp_call0(const char *name) { void *f = ipp_lookup(name); return f ? ((int (*)(void))f)() : -1; }']
os.makedirs(f'{HERE}/src/gen', exist_ok=True)
open(f'{HERE}/src/gen/ipp_table.c', 'w').write('\n'.join(out) + '\n')
print(f'table: {len(names)} names, implemented {len([n for n in names if n in impl])}, stubs {len(stubs)}; header-only (not in FL table): {missing_impl}')
