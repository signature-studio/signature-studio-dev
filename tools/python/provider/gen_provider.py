#!/usr/bin/env python3
"""flapi_table.json + flapi_ids.json -> provider/gen/fl_table.c (fn_id 順の関数記述子表)。

  python3 provider/gen_provider.py [--check-handlers fl_engine.c ...]

- 添字 = flapi_ids.json の fn_id。ids と table の列挙順が食い違ったら失敗する。
- analysis/ilmcp/{plugin_catalog,highlight_names}.json から gen/ilmcp_data.h (ilmcp の browser 木・
  プラグイン名・highlight 名) を生成する。木の子の順は host/ilmcp.mjs の walk と同じ (名前の大小無視順)。
- 記述子: 戻り型 (署名 returns)・引数数 (np/nmin)・引数型列。署名なし (新規 43 + ilmcp) は np=-1。
- ハンドラ `h_<module>_<name>` は weak 参照。未実装は NULL → fl_api_call が "Unspecified error" を返す。
- --check-handlers: ソース中の FL_H(mod, name) が全て表に存在することを検査する (綴り誤りで weak が
  黙って NULL になるのを防ぐ)。
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FLAPI = os.path.join(HERE, "..", "analysis", "flapi")
OUT = os.path.join(HERE, "gen", "fl_table.c")
ILMCP_IN = os.path.join(HERE, "..", "analysis", "ilmcp")
ILMCP_OUT = os.path.join(HERE, "gen", "ilmcp_data.h")
ROOT_NAME = "Plugin database"


def _key(s):
    return (s.lower(), s)


def write_ilmcp():
    cat = json.load(open(os.path.join(ILMCP_IN, "plugin_catalog.json")))["entries"]
    hl = json.load(open(os.path.join(ILMCP_IN, "highlight_names.json")))["names"]
    for s in [e["name"] for e in cat] + hl:
        assert s.isascii() and not any(ch in s for ch in '/\\"'), s
    # 木と walk は host/ilmcp.mjs (buildTree / walk) と同じ。結果 (非再帰 / 再帰) を事前計算して表にする。
    tree = {}
    for e in cat:
        n = tree
        for d in e["path"]:
            n = n.setdefault("dirs", {}).setdefault(d, {})
        n.setdefault("items", []).append(e["name"])

    def walk(node, prefix, recursive, out):
        for d in sorted(node.get("dirs", {}), key=_key):
            out.append(f"{prefix}{d}/")
            if recursive:
                walk(node["dirs"][d], f"{prefix}{d}/", True, out)
        for name in sorted(node.get("items", []), key=_key):
            out.append(f"{prefix}{name}")

    rows = []

    def visit(node, key):
        flat = {0: [], 1: []}
        for r in (0, 1):
            walk(node, "", bool(r), flat[r])
        rows.append((key, flat[0], flat[1]))
        for d in node.get("dirs", {}):
            visit(node["dirs"][d], f"{key}/{d}" if key else d)

    visit(tree, "")
    cstr = lambda s: '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
    lines = ["/* generated by provider/gen_provider.py — 編集しない (入力: analysis/ilmcp/ の 2 JSON) */",
             "typedef struct { const char *key; const char *const *flat0; const char *const *flat1; } ilmcp_dir;",
             "typedef struct { const char *kind, *name; } ilmcp_plugin;"]
    for i, (_, f0, f1) in enumerate(rows):
        for tag, lst in (("a", f0), ("b", f1)):
            lines.append(f"static const char *const ild_{i}{tag}[] = {{" + "".join(cstr(x) + ", " for x in lst) + "NULL};")
    lines.append("static const ilmcp_dir ilmcp_dirs[] = {")
    for i, (key, _, _) in enumerate(rows):
        lines.append(f"    {{{cstr(key)}, ild_{i}a, ild_{i}b}},")
    lines.append("};")
    lines.append(f"const int ilmcp_dir_n = {len(rows)};")
    lines.append("static const ilmcp_plugin ilmcp_plugins[] = {")
    for e in cat:
        lines.append(f"    {{{cstr(e['kind'])}, {cstr(e['name'])}}},")
    lines.append("};")
    lines.append(f"const int ilmcp_plugin_n = {len(cat)};")
    lines.append("static const char *const ilmcp_highlights[] = {" + "".join(cstr(s) + ", " for s in hl) + "NULL};")
    lines.append(f"const int ilmcp_highlight_n = {len(hl)};")
    open(ILMCP_OUT, "w").write("\n".join(lines) + "\n")
    return len(rows), len(cat), len(hl)

TYPE = {"int": "i", "bool": "b", "float": "f", "str": "s"}
RET = {"None": "n", "int": "i", "bool": "b", "float": "f", "str": "s"}


def main():
    t = json.load(open(os.path.join(FLAPI, "flapi_table.json")))
    ids = json.load(open(os.path.join(FLAPI, "flapi_ids.json")))
    flat = [f"{m}.{n}" for m, fs in t["modules"].items() for n in fs]
    if flat != ids:
        sys.exit("flapi_ids.json の順序が flapi_table.json の列挙順と一致しない")
    assert len(ids) == t["function_total"] == 435, len(ids)

    lines = ['/* generated by provider/gen_provider.py — 編集しない */', '#include "../fl_api.h"', ""]
    decl, rows = [], []
    for fid, key in enumerate(ids):
        mod, name = key.split(".")
        assert re.fullmatch(r"\w+", mod) and re.fullmatch(r"\w+", name), key
        sig = t["modules"][mod][name].get("sig")
        h = f"h_{mod}_{name}"
        decl.append(f"extern int {h}(fl_call *) __attribute__((weak));")
        if sig is None:
            ret, np_, nmin, pt = "a", -1, 0, ""
        else:
            ps = sig["params"]
            ret = RET.get(sig["returns"], "a")
            np_ = len(ps)
            nmin = sum(1 for p in ps if p.get("default") is None)
            pt = "".join(TYPE.get(p["type"], "a") for p in ps)
        rows.append(f'    /*{fid:3d}*/ {{"{mod}", "{name}", \'{ret}\', {np_}, {nmin}, "{pt}", {h}}},')
    lines += decl + ["", "const fl_desc fl_table[] = {"] + rows + ["};",
                                                              f"const int fl_table_n = {len(ids)};", ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines))
    dirs, plugins, hls = write_ilmcp()

    defined = set()
    for src in sys.argv[2:] if len(sys.argv) > 1 and sys.argv[1] == "--check-handlers" else []:
        for m in re.finditer(r"FL_H\(\s*(\w+)\s*,\s*(\w+)\s*\)", open(src).read()):
            defined.add(f"{m.group(1)}.{m.group(2)}")
    bad = sorted(defined - set(ids))
    if bad:
        sys.exit(f"表に無いハンドラ: {bad}")
    print(f"fl_table.c: {len(ids)} 関数, ハンドラ {len(defined)}; ilmcp_data.h: dir {dirs}, plugin {plugins}, highlight {hls}")


if __name__ == "__main__":
    main()
