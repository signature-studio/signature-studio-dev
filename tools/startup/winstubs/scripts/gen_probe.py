#!/usr/bin/env python3
"""data/api_matrix.tsv から link probe の C を生成する (argv[1] = 出力 .c)。
各 API の「リンク時アドレス」と GetProcAddress(dll, name) の一致を 1 行ずつ出力するプログラム。
未解決の API があれば emcc の ERROR_ON_UNDEFINED_SYMBOLS で リンク自体が失敗する (= リンクテスト)。"""
import sys, csv, os
here = os.path.dirname(os.path.abspath(__file__))
rows = [r for r in csv.reader(open(os.path.join(here, '..', 'data', 'api_matrix.tsv')), delimiter='\t') if r and not r[0].startswith('#')]
out = ['/* generated by scripts/gen_probe.py — 手編集禁止 */', '#include <stdio.h>', '#include <string.h>', '#include <stdint.h>',
       'void* GetProcAddress(void*, const char*) __asm__("GetProcAddress");',
       'void* ws_GetModuleHandleA(const char*) __asm__("GetModuleHandleA");',
       'extern void winstubs_init(const void*);', '']
ents = []
for i, r in enumerate(rows):
    api, dll, grp, gate, impl, gpa = r[:6]
    sym = 'winstubs_cpuid' if api == 'cpuid' else api
    out.append('extern void ws_p%d(void) __asm__("%s");' % (i, sym))
    ents.append((i, api, dll, gpa))
out.append('typedef struct { const char* api; const char* dll; const char* gpa; void* addr; } Ent;')
out.append('static const Ent ents[] = {')
for i, api, dll, gpa in ents:
    out.append('    { "%s", "%s", "%s", (void*)ws_p%d },' % (api, dll, gpa, i))
out.append('};')
out.append('''int main(void) {
    winstubs_init(0);
    int bad = 0;
    for (unsigned i = 0; i < sizeof ents / sizeof ents[0]; i++) {
        const Ent* e = &ents[i];
        const char* g = "-";
        int same = -1;
        if (strcmp(e->dll, "-")) {
            void* m = ws_GetModuleHandleA(e->dll);
            void* p = m ? GetProcAddress(m, e->api) : 0;
            g = p ? "y" : "n";
            same = p ? (p == e->addr) : -1;
        }
        printf("%s\\tlinked=%d\\tgpa=%s\\tsame=%d\\n", e->api, e->addr != 0, g, same);
        if (e->addr == 0) bad++;
    }
    return bad ? 1 : 0;
}''')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
