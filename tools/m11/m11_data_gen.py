#!/usr/bin/env python3
# M11 #7: FLEngine (block00031_PE.bin) の画像データ (.data/.rdata) を wasm linear memory
# の LVA (= VA - 0x400000) 通りに敷設する C shim を生成する (m6_data_gen.py pattern の copy).
#   - 敷設先: IR 側 M1/M2 pass が @global_var / 定数 inttoptr を LVA (RVA) に remap 済なので
#     画像先頭 (image base 0x400000) が linear 0 に来る配置とする
#   - on-disk の 8B pointer 値は preferred base (0x400000) 寄生 → LVA (= RVA) に -0x400000 補正
#     (補正位置は .reloc (IMAGE_REL_BASED_DIR64=10) の RVA 表から取得; m6 と同一手法)
# 出力: work/m11_data.c (m11_data_install(): 一度だけ, lifted 関数を呼ぶ前に必須)
import sys, os, struct

BASE = os.path.dirname(os.path.abspath(__file__))
WINF = '/home/ubuntu/work/analysis/win64/extracted/block00031_PE.bin'
OUT = os.path.join(BASE, 'work', 'm11_data.c')

IMG_BASE = 0x400000        # preferred image base
LVA_SH = 0x400000          # linear = VA - LVA_SH


def main():
    W = __import__('ottlib').Bin(WINF) if False else None
    sys.path.insert(0, '/home/ubuntu/work/webstudio/tools/m6')
    from ottlib import Bin
    W = Bin(WINF)
    secs = []
    for (n, lo, data) in W.sections:
        if n in ('.rdata', '.data'):
            secs.append((n, lo, bytearray(data)))
    # .reloc DIR64 収集
    relocs = []
    for (n, lo, data) in W.sections:
        if n != '.reloc':
            continue
        i = 0
        while i + 8 <= len(data):
            page, blksz = struct.unpack_from('<II', data, i)
            if (blksz == 0 or blksz < 8 or page == 0):
                break
            for k in range((blksz - 8) // 2):
                e = struct.unpack_from('<H', data, i + 8 + k * 2)[0]
                typ, off = (e >> 12), (e & 0xfff)
                if typ == 10:
                    relocs.append(page + off)
            i += blksz
    counts = {}
    for (n, lo, sd) in secs:
        c = 0
        for r in relocs:
            if lo <= r < lo + len(sd) - 8:
                off = r - lo
                v = struct.unpack_from('<Q', sd, off)[0]
                nt = v - LVA_SH
                if LVA_SH < v < LVA_SH + 0x1ac0000:
                    sd[off:off + 8] = struct.pack('<Q', nt)
                    c += 1
        counts[n] = c
    print('[data] reloc DIR64: %d 修整 (.rdata=%d .data=%d)' % (
        len(relocs), counts.get('.rdata', 0), counts.get('.data', 0)))
    parts = [
        '/* auto-generated by m11_data_gen.py: FLEngine_x64.dll (block00031_PE.bin) の .rdata/.data を\n'
        ' * LVA (= VA - 0x400000) 通りに wasm linear memory へ敷設する。\n'
        ' * 8B pointer 値 (on-disk: preferred base 0x400000) は LVA (= RVA) に補正済 (.reloc 基準)。\n'
        ' *   m11_data_install(): 一度だけ (lifted 関数を呼ぶ前に必須)。\n'
        ' */\n',
        '#include <stdint.h>\n#include <stddef.h>\n#include <string.h>\n',
    ]
    for (n, lo, sd) in secs:
        sym = n.replace('.', '_')
        parts.append('static const unsigned char dlld_%s[] = {\n' % sym)
        rows = [','.join('0x%02x' % b for b in sd[i:i + 16]) for i in range(0, len(sd), 16)]
        parts.append(',\n'.join(rows))
        parts.append('\n};\n')
        parts.append('#define %s_LO 0x%xu\n' % (sym.upper(), lo))
        parts.append('#define %s_LEN %du\n' % (sym.upper(), len(sd)))
    parts.append('\nvoid m11_data_install(void) {\n')
    for (n, lo, sd) in secs:
        sym = n.replace('.', '_')
        parts.append('  memcpy((void*)0x%xu, dlld_%s, %du);\n' % (lo, sym, len(sd)))
    parts.append('}\n')
    open(OUT, 'w').write(''.join(parts))
    print('[data] wrote %s (%d KB)' % (OUT, os.path.getsize(OUT) >> 10))


if __name__ == '__main__':
    main()
