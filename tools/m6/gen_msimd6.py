#!/usr/bin/env python3
"""gen_msimd6.py (M6b 版): lift IR の declare から msimd6.c を生成する.

M6b 改修点:
  - helper signature を lift IR 宣言 (既定 work/ott_shift3b.ll) からそのまま採用。
    旧版は名称から推定していたため vmovdqa__16 (i256x 返し) / movups__1 (i64 返し)
    / subsd (i128,i64) 等の signature 不一致を生じていた。宣言駆動化で
    wasm-ld: function signature mismatch の __asm_* 側 5 種は構造的に消滅。
  - i256 宣言 (vmovdqu/vmovdqa/vmovntdq) は SKIP: m6_memfix.py が CRT memmoveの
    define を C 実装へ置換するため IR から i256 呼出 site が消滅。C には i256 正体
    型がなく (_BitInt(256) 非対応) ABI を一致させられないため。
  - 旧 msimd6.c の C 破損 (`void r = 0; return r;` 等) と意味乱れ (pand→xor,
    vsubsd__13 '+', vmulsd__14 '+', movsd__11/vmovsd__32 の f32 blend,
    cvtdq2pd の f32 cast, movups__1 の i64 返し) を修正。
  - 生成物の整合照合は m6_simd_check.py (declare/定義/呼出 site 3 重照合)。

使い方: python3 gen_msimd6.py [SRC_LL]  (既定 work/ott_shift3b.ll)
"""
import re
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'work/ott_shift3b.ll'

ll = open(SRC).read()
SIGS = re.findall(r"(?m)^declare (\S+) @(__asm_[\w.\-]+)\((.*?)\) local_unnamed_addr$", ll)
SIGS.sort(key=lambda s: s[1])
print('[gen] declares:', len(SIGS), file=sys.stderr)

TYMAP = {'i128': 'u128', 'i64': 'u64', 'i32': 'u32', 'i8': 'u8', 'void': 'void'}
LETTERS = ['a', 'b', 'c', 'f', 'm', 'n']


def parse_args(args):
    out = []
    for tok in [x.strip() for x in args.split(',') if x.strip()]:
        out.append(tok.split()[0])
    return out


def params(types):
    if not types:
        return 'void'
    p = ', '.join(f'{TYMAP.get(t, t)} {LETTERS[i]}' for i, t in enumerate(types))
    return p


out = ['/* msimd6.c — OTT (win64 VST2) lift の __asm_* helpers 完全版。',
       ' * generated by gen_msimd6.py from: ' + SRC,
       ' *  - signature: lift IR 宣言そのまま (RetDec の i64/i32 返り値・i64 即値引数を保持)',
       ' *  - i256 (vmovdqu/vmovdqa/vmovntdq) は定義しない: 呼出 site は m6_memfix.py が',
       ' *    CRT memmove C 実装化により消滅させる (m6_simd_check.py で残呼出 0 を検収)。',
       ' *  - comis/ucomis 系は no-op (CF/ZF/PF は ir6_pass.py [P1] が IR 内で fcmp 化)',
       ' *  - mxcsr 系は no-op (wasm では rounding/例外マスク制御不可; native は DLL 実機)',
       ' */',
       '#include "msimd6_core.h"',
       '']

implemented, skipped, unimplemented = [], [], []
for (ret, full, args) in SIGS:
    nm = full[len('__asm_'):]
    types = parse_args(args)
    P = params(types)
    R = TYMAP.get(ret, ret)
    if 'i256' in types or ret == 'i256':
        skipped.append('%s(%s)(%s)' % (nm, ret, ','.join(types)))
        continue
    body = None
    comm = None

    # ===== misc / 制御 =====
    if nm == 'int3':
        body, comm = ['return 0;'], 'int3/ud2 — RetDec が i64 返り値でモデル化'
    elif nm == 'int' and types == ['i8']:
        body, comm = ['(void)a;'], 'int — no-op (declare 型を維持)'
    elif nm.startswith('sfence'):
        body = ['return 0;']
    elif 'movnt' in nm:
        body, comm = ['(void)a; (void)b;'], 'non-temporal store — S1 (ir5_patch) 由来 residual (declare 型維持)'
    elif 'mxcsr' in nm:
        body, comm = ['(void)0;'], 'wasm では MXCSR を制御できない — no-op'
    elif 'comis' in nm:
        body, comm = ['(void)0;'], 'comis/ucomis — flag は ir6_pass.py [P1] が IR level で解決 (no-op)'
    elif 'cmplesd' in nm or 'cmpnltsd' in nm or 'vcmplesd' in nm or 'vcmpnltsd' in nm:
        comm = 'cmpsd mask 形 (predicate は name から; SRC2 = m64 bits)'
        body = ['return _cmpsd_mask(a, b, _cmpsd_pred("' + nm + '", ' + str(len(nm)) + '));']

    # ===== move / load / extract =====
    elif nm in ('movaps', 'movapd', 'movdqa', 'movdqu', 'movups__1',
                'movaps__4', 'movapd__5', 'movdqa__10', 'movdqu__3',
                'vmovdqa__16', 'vmovapd', 'vmovdqu__33'):
        cast = '' if ret == 'i128' else '(u64)'
        body = ['return %sa;' % cast]
        comm = 'identity (load 印)'
    elif nm == 'movups' and types == ['i128', 'i128']:
        body, comm = ['(void)a; (void)b;'], 'store 型 residual (S1 修復対象外残). dst=0 dead-store no-op'
    elif nm in ('movsd', 'movq', 'vmovsd', 'vmovq__23'):
        body = ['return set_u64_lo(a);']
        comm = 'load: 低 64bit 設置'
    elif nm in ('movd', 'movss', 'vmovd__34'):
        body = ['return set_u32_lo(a);']
        comm = 'load: 低 32bit 設置'
    elif nm in ('movsd__2', 'movss__17', 'movq__6', 'movq__26', 'vmovq'):
        body = ['return (u64)a;']
        comm = 'extract: 低 64bit'
    elif nm in ('movd__28', 'vmovd'):
        body = ['return (u32)(u64)a;']
        comm = 'extract: 低 32bit'
    elif nm in ('movsd__11', 'vmovsd__32'):
        body = ['return _overwrite_lo64(a, lane0_u(b));']
        comm = 'movsd xmm1,xmm2: 低 64bit のみ src から'
    elif nm == 'movss__30':
        body = ['u128 r = a; memcpy(&r, &b, 4); return r;']
        comm = 'movss xmm1,xmm2: 低 32bit のみ src から'

    # ===== scalar f64 (即值 operand= i64 double bits) =====
    elif nm in ('subsd', 'mulsd', 'addsd', 'divsd__19', 'vsubsd', 'vmulsd', 'vaddsd__21'):
        op = {'subsd': '-', 'vsubsd': '-', 'mulsd': '*', 'vmulsd': '*',
              'addsd': '+', 'vaddsd__21': '+', 'divsd__19': '/'}[nm]
        body = ["return _laneop64c2(a, asd(b), '%s');" % op]
    elif nm in ('subsd__7', 'mulsd__8', 'addsd__9', 'divsd', 'vsubsd__13', 'vmulsd__14', 'vdivsd', 'vaddsd'):
        op = {'subsd__7': '-', 'vsubsd__13': '-', 'mulsd__8': '*', 'vmulsd__14': '*',
              'addsd__9': '+', 'vaddsd': '+', 'divsd': '/', 'vdivsd': '/'}[nm]
        body = ["return _laneop64(a, b, '%s');" % op]
    elif nm == 'maxsd':
        body = ['return _dmax_sd(a, b);']
    elif nm in ('addpd', 'vaddpd', 'mulpd', 'vmulpd'):
        op = {'addpd': '+', 'vaddpd': '+', 'mulpd': '*', 'vmulpd': '*'}[nm]
        body = ["return _lanepd(a, b, '%s');" % op]

    # ===== scalar f32 =====
    elif nm in ('mulss', 'addss', 'subss', 'divss'):
        op = {'mulss': '*', 'addss': '+', 'subss': '-', 'divss': '/'}[nm]
        body = ["return _laneop32(a, b, '%s');" % op]
    elif nm in ('mulss__18', 'addss__31', 'subss__35', 'vaddss', 'vmulss'):
        op = {'mulss__18': '*', 'vmulss': '*', 'addss__31': '+', 'vaddss': '+', 'subss__35': '-'}[nm]
        body = ["return _laneop32c(a, asf(b), '%s');" % op]
    elif nm == 'maxss':
        body = ['return _fmax_ss(a, b);']
    elif nm == 'minss':
        body = ['return _fmin_ss(a, b);']

    # ===== FMA (Intel 132/213/231 規約, dst = 第 1 引数 a) =====
    elif nm.startswith('vfmadd') or nm.startswith('vfnmadd') or nm.startswith('vfmsub') or nm.startswith('vfnmsub'):
        FMAFAM = {
            'vfmadd132sd': '_fma132sd', 'vfmsub132sd': '_fms132sd',
            'vfnmadd132sd': '_fnm132sd', 'vfnmsub132sd': '_fnms132sd',
            'vfmadd213sd': '_fma213sd', 'vfmsub213sd': '_fms213sd',
            'vfnmadd213sd': '_fnm213sd', 'vfnmsub213sd': '_fnms213sd',
            'vfmadd231sd': '_fma231sd', 'vfmsub231sd': '_fms231sd',
            'vfnmadd231sd': '_fnm231sd', 'vfnmsub231sd': '_fnms231sd',
        }
        base = nm.split('__')[0]
        fam = FMAFAM.get(base)
        if fam is None:
            unimplemented.append(nm)
            continue
        cexpr = 'asd(c)' if types[-1] == 'i64' else 'lane0_d(c)'
        body = ['return %s(a, b, %s);' % (fam, cexpr)]
        comm = base + ' — fma() 単一丸め (FMA3 hardware 等価)'

    # ===== shuffle / unpack / blend =====
    elif nm in ('pshufd', 'vpshufd'):
        comm = 'pshufd: 32bit lane shuffle (imm 2bit 単位)'
        body = ['u32 la[4], lr[4];',
                'memcpy(la, &a, 16);',
                'lr[0] = la[(b >> 0) & 3]; lr[1] = la[(b >> 2) & 3];',
                'lr[2] = la[(b >> 4) & 3]; lr[3] = la[(b >> 6) & 3];',
                'u128 r128; memcpy(&r128, lr, 16); return r128;']
    elif nm == 'vshufps':
        comm = 'vshufps: 低 2lane = a, 上 2lane = b (imm で select)'
        body = ['v4f a4, b4; union { float f; u32 u; } c0, c1, c2, c3;',
                'memcpy(&a4, &a, 16); memcpy(&b4, &b, 16);',
                'c0.f = a4[(c >> 0) & 3]; c1.f = a4[(c >> 2) & 3];',
                'c2.f = b4[(c >> 4) & 3]; c3.f = b4[(c >> 6) & 3];',
                'u32 r32[4] = { c0.u, c1.u, c2.u, c3.u };',
                'u128 r128; memcpy(&r128, r32, 16); return r128;']
    elif nm == 'movlhps':
        body = ['return _overwrite_hi64(a, lane0_u(b));']
    elif nm == 'movhlps':
        body = ['return _overwrite_lo64(a, lane1_u(b));']
    elif nm in ('unpcklpd', 'vunpcklpd'):
        body = ['return lane0_u(a) | ((u128)lane0_u(b) << 64);']
    elif nm == 'punpcklbw':
        comm = 'punpcklbw: 8bit interleave (低位 8 byte)'
        body = ['v16b a4, b4, r4; memcpy(&a4, &a, 16); memcpy(&b4, &b, 16);',
                'for (int i = 0; i < 8; i++) { r4[2*i] = a4[i]; r4[2*i+1] = b4[i]; }',
                'u128 r128; memcpy(&r128, &r4, 16); return r128;']
    elif nm in ('punpckldq', 'vpunpckldq'):
        comm = 'punpckldq: 32bit interleave (lane 0..1)'
        body = ['u32 xa[2], xb[2], xr[4] = { 0, 0, 0, 0 };',
                'memcpy(xa, &a, 8); memcpy(xb, &b, 8);',
                'xr[0] = xa[0]; xr[1] = xb[0]; xr[2] = xa[1]; xr[3] = xb[1];',
                'u128 r128; memcpy(&r128, xr, 16); return r128;']

    # ===== 整数 lane 演算 =====
    elif nm in ('paddq', 'vpaddq'):
        body = ['return _laneaddq(a, b);']
    elif nm in ('psubq', 'vpsubq'):
        body = ['return _lanesubq(a, b);']
    elif nm == 'psubd':
        body = ['return _lanesubd(a, b);']
    elif nm in ('psrlq', 'vpsrlq'):
        comm = 'psrlq: 64bit lane 右論理シフト (RetDec は imm を bit 数のまま渡す; IR 実測 imm=52)'
        body = ['b &= 63;',
                'return _overwrite_hi64(_overwrite_lo64(a, lane0_u(a) >> b), lane1_u(a) >> b);']
    elif nm == 'psllq':
        comm = 'psllq: 64bit lane 左論理シフト (imm は bit 数)'
        body = ['b &= 63;',
                'return _overwrite_hi64(_overwrite_lo64(a, lane0_u(a) << b), lane1_u(a) << b);']
    elif nm in ('psrldq', 'vpsrldq'):
        comm = 'psrldq: 全 128bit を 8*n bit 右シフト (byte シフト)'
        body = ['return a >> ((u128)(u32)(8u * b));']
    elif nm == 'vpmovsxdq':
        comm = 'vpmovsxdq: 2x i32 → 2x i64 符号拡張'
        body = ['i32 l0 = (i32)(u32)a, l1 = (i32)(u32)(a >> 32);',
                'return (u128)((u64)(i64)l0) | ((u128)((u64)(i64)l1) << 64);']

    # ===== 論理 =====
    elif nm in ('pand', 'vpand', 'andps', 'andpd', 'vandps', 'vandpd'):
        body = ['return a & b;']
    elif nm in ('pxor', 'vpxor', 'xorps', 'xorpd', 'vxorps', 'vxorpd'):
        body = ['return a ^ b;']
    elif nm in ('por', 'vpor', 'orps', 'vorps'):
        body = ['return a | b;']

    # ===== 変換 =====
    elif nm in ('cvtps2pd', 'vcvtps2pd'):
        body = ['v4f a4; v2d r2; memcpy(&a4, &a, 16);',
                'r2[0] = (double)a4[0]; r2[1] = (double)a4[1];',
                'u128 r128; memcpy(&r128, &r2, 16); return r128;']
    elif nm in ('cvtdq2pd', 'vcvtdq2pd'):
        comm = 'cvtdq2pd: 低位 2x i32 → 2x f64 (旧版の f32→f64 cast は誤り; M6b 修正)'
        body = ['v2d r2; r2[0] = (double)(i32)(u32)a; r2[1] = (double)(i32)(u32)(a >> 32);',
                'u128 r128; memcpy(&r128, &r2, 16); return r128;']
    elif nm in ('cvtpd2ps', 'vcvttpd2dq', 'cvttpd2dq'):
        body = ['v2d a2; v4f r4; memcpy(&a2, &a, 16);',
                'r4[0] = (float)a2[0]; r4[1] = (float)a2[1]; r4[2] = 0; r4[3] = 0;',
                'u128 r128; memcpy(&r128, &r4, 16); return r128;']
    elif nm in ('cvtss2sd', 'vcvtss2sd'):
        if types == ['i128']:
            body = ['return _overwrite_lo64(a, das((double)lane0_f(a)));']
        else:
            body = ['return _overwrite_lo64(a, das((double)lane0_f(b)));']
    elif nm in ('cvtsd2ss', 'vcvtsd2ss'):
        if types == ['i128']:
            body = ['return lane0f_set(a, (float)lane0_d(a));']
        else:
            body = ['return lane0f_set(a, (float)lane0_d(b));']
    elif nm in ('cvttsd2si', 'vcvttsd2si'):
        body = ['return (i32)(i64)lane0_d(a);']
    elif nm in ('cvtss2si', 'vcvtss2si'):
        body = ['return (i32)(i64)lane0_f(a);']
    elif nm == 'cvtsi2ss' or (nm == 'vcvtsi2ss' and types == ['i32']):
        body = ['return set_u32_lo(fas((float)(i32)a));']
    elif nm == 'vcvtsi2ss':
        body = ['return lane0f_set(a, (float)(i32)b);']

    # ===== sqrt / round =====
    elif nm == 'sqrtss':
        body = ['return lane0f_set(a, sqrtf(lane0_f(a)));']
    elif nm == 'sqrtss__20':
        body = ['return set_u32_lo(fas(sqrtf(asf(a))));']
    elif nm == 'sqrtsd':
        body = ['return set_u64_lo(das(sqrt(asd(a))));']
    elif nm == 'sqrtpd':
        body = ['v2d a2; memcpy(&a2, &a, 16);',
                'a2[0] = sqrt(a2[0]); a2[1] = sqrt(a2[1]);',
                'u128 r128; memcpy(&r128, &a2, 16); return r128;']
    elif nm == 'vroundsd':
        comm = 'vroundsd: b の lane0 を imm 低 2bit の丸めモードで round'
        body = ['return lane0d_set(a, _round_pd(lane0_d(b), c & 3));']
    elif nm == 'vmovapd__22':
        body, comm = ['(void)a; (void)b;'], 'store 型 residual — no-op'

    else:
        unimplemented.append(nm)
        continue

    # ===== emit =====
    if comm:
        out.append('/* ' + comm + ' */')
    out.append('EMSCRIPTEN_KEEPALIVE ' + R + ' __asm_' + nm + '(' + P + ')')
    out.append('{')
    out.extend('    ' + st for st in body)
    out.append('}')
    implemented.append(nm)

out.append('')
open('msimd6.c', 'w').write('\n'.join(out) + '\n')
print('[gen] implemented:', len(implemented), file=sys.stderr)
print('[gen] skipped (i256):', len(skipped), file=sys.stderr)
for s in skipped:
    print('    skip:', s, file=sys.stderr)
print('[gen] UNIMPLEMENTED (fail-fast):', len(unimplemented), unimplemented, file=sys.stderr)
print('wrote msimd6.c (%d lines)' % len(out), file=sys.stderr)
