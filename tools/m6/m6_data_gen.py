#!/usr/bin/env python3
# M6 #3: DLL データ (.rdata/.data) を wasm linear memory の VA (= image base 0x400000 + RVA)
# 通りに敷設する C shim を生成する.
#   - on-disk の 8B pointer 値は image base 0x180000000 寄生 → wasm linear (0x400000+RVA) に補正
#   - 補正位置は .reloc (IMAGE_REL_BASED_DIR64) の RVA 表から取得
# 出力: work/m6_data.c
import sys, os, struct

BASE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'shared'))
from paths import PLUGINS_DIR
WINF = os.environ.get('M6_PE', f'{PLUGINS_DIR}/ott/binaries/OTT_vst2_win64.dll')
OUT = os.environ.get('M6_DATA_OUT', os.path.join(BASE, 'work', 'm6_data.c'))

IMG_BASE = int(os.environ.get('M6_IMG_BASE', '0x180000000'), 0)    # on-disk pointer 値の寄生 base (実測)
VA_BASE = 0x30000000       # IR shift後の DLL 実体配置先 (= ir6_shift.py の NEWBASE)

def main():
    W = __import__('ottlib').Bin(WINF)
    secs = []
    for (n, lo, data) in W.sections:
        if n in ('.rdata', '.data'):
            secs.append((n, lo, bytearray(data)))
    # .reloc
    relocs = []
    for (n, lo, data) in W.sections:
        if n != '.reloc':
            continue
        i = 0
        while i + 8 <= len(data):
            page, blksz = struct.unpack_from('<II', data, i)
            if (blksz == 0 or blksz < 8 or page == 0):
                break
            for k in range((blksz - 8) // 2):
                e = struct.unpack_from('<H', data, i + 8 + k * 2)[0]
                typ, off = (e >> 12), (e & 0xfff)
                if typ == 10:
                    relocs.append(page + off)
            i += blksz
    counts = {}
    for (n, lo, sd) in secs:
        c = 0
        for r in relocs:
            if lo <= r <= lo + len(sd) - 8:  # #593: セクション末尾の 8B slot も対象 (旧 `<` は off-by-one, m11 #572 と同根)
                off = r - lo
                v = struct.unpack_from('<Q', sd, off)[0]
                nt = v - IMG_BASE + VA_BASE
                if 0x400000 <= nt < 0x180000000:
                    sd[off:off + 8] = struct.pack('<Q', nt)
                    c += 1
        counts[n] = c
    print('[data] reloc DIR64: %d 修整 (.rdata=%d .data=%d)' % (
        len(relocs), counts.get('.rdata', 0), counts.get('.data', 0)))
    parts = [
        '/* auto-generated by m6_data_gen.py: OTT_vst2_win64.dll の .rdata/.data を\n'
        ' * VA (= 0x400000 + RVA) 通りに wasm linear memory へ敷設する。\n'
        ' * 8B pointer 値 (on-disk: 0x180000000 parasit) は 0x400000+RVA に補正済 (.reloc 基準)。\n'
        ' *   m6_data_install(): 一度だけ (lifted 関数を呼ぶ前に必須)。\n'
        ' */\n',
        '#include <stdint.h>\n#include <stddef.h>\n#include <string.h>\n',
        '#include "../m6_types.h"\n',
    ]
    for (n, lo, sd) in secs:
        sym = n.replace('.', '_')
        parts.append('static const unsigned char dlld_%s[] = {\n' % sym)
        rows = [','.join('0x%02x' % b for b in sd[i:i + 16]) for i in range(0, len(sd), 16)]
        parts.append(',\n'.join(rows))
        parts.append('\n};\n')
        parts.append('#define %s_LO 0x%xu\n' % (sym.upper(), VA_BASE + lo))
        parts.append('#define %s_LEN %du\n' % (sym.upper(), len(sd)))
    parts.append('\nvoid m6_data_install(void) {\n')
    for (n, lo, sd) in secs:
        sym = n.replace('.', '_')
        parts.append('  memcpy((void*)0x%xu, dlld_%s, %du);\n' % (VA_BASE + lo, sym, len(sd)))
    parts.append('}\n')
    open(OUT, 'w').write(''.join(parts))
    print('[data] wrote %s (%d KB)' % (OUT, os.path.getsize(OUT) >> 10))


if __name__ == '__main__':
    main()
