ck('E9 audioMaster: version=0x960, vendor ver=0x271a, "Fruity_Wrapper"/"Image_Line" 文字列, canDo 表', '0x960' in a and '0x271a' in a and 'sendVstEvents' in a and 'receiveVstTimeInfo' in a)
