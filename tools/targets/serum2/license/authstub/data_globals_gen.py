#!/usr/bin/env python3
"""harness .ll が参照する外部定数 global を PE から抽出して data_globals.c を生成する。
各 global は max(型サイズ, 256B) で PE 実バイトから切り出し (隣接参照を吸収)。16B align。
@__authstub_* (LF1/LF2 束縛先) は harness C 側で定義するためここでは生成しない。
usage: data_globals_gen.py <in.ll> <pe> <out.c>
"""
import re, sys
import pefile

ll_path, pe_path, out_path = sys.argv[1], sys.argv[2], sys.argv[3]
ll = open(ll_path).read()

defined = set(re.findall(r'^@([\w.]+)\s*=\s*(?:unnamed_addr\s+)?(?:local_unnamed_addr\s+)?(?:constant|global)', ll, re.M))
used = set(re.findall(r'@([\w.]+)', ll))
ext = sorted(u for u in used - defined if u.startswith(('global_var_', '_DAT_')))

pe = pefile.PE(pe_path, fast_load=True)
IMG = pe.OPTIONAL_HEADER.ImageBase
S = sorted(pe.sections, key=lambda s: s.VirtualAddress)
dm = pe.get_memory_mapped_image()

def read_bytes(va, n):
    rva = va - IMG
    for s in S:
        if s.VirtualAddress <= rva < s.VirtualAddress + max(s.Misc_VirtualSize, len(s.get_data())):
            off = rva - s.VirtualAddress
            d = bytes(s.get_data()[off:])
            return d[:n]
    return b''

def type_size(sym):
    m = re.search(r'getelementptr inbounds \(\[(\d+) x i(\d+)\], (?:ptr|i\d+\*) @' + re.escape(sym) + r'\b', ll)
    if m:
        return int(m.group(1)) * int(m.group(2)) // 8
    m = re.search(r'^@' + re.escape(sym) + r'\s*=\s*external[^\n]*?(?:constant|global)\s+(.+?)$', ll, re.M)
    if m:
        t = m.group(1)
        mm = re.match(r'\[(\d+) x (i(\d+)|ptr)\]', t)
        if mm:
            w = 8 if mm.group(2) == 'ptr' else int(mm.group(3)) // 8
            return int(mm.group(1)) * w
        mm = re.match(r'i(\d+)', t)
        if mm:
            return int(mm.group(1)) // 8
        if re.match(r'ptr$', t):
            return 8
    return 8

out = ['/* auto-generated by data_globals_gen.py — PE 実バイト (max(type,256B), 16B align) */',
       '#include <stdint.h>', '']
for sym in ext:
    m = re.search(r'([0-9a-f]{9})$', sym)
    if not m:
        raise SystemExit('cannot parse VA from ' + sym)
    va = int(m.group(1), 16)
    n = max(type_size(sym), 256)
    raw = read_bytes(va, n)
    if len(raw) < n:
        raise SystemExit('short read @%x: %d/%d' % (va, len(raw), n))
    vals = ','.join(str(b) for b in raw)
    out.append(f'const uint8_t {sym}[{n}] __attribute__((aligned(16))) = {{{vals}}};')
    out.append(f'const void *const _ref_{sym} = {sym}; /* 引用確保 (LTO 削除防止) */')

open(out_path, 'w').write('\n'.join(out) + '\n')
print('data_globals_gen: %d globals -> %s' % (len(ext), out_path))
