#!/usr/bin/env python3
"""SR-3 step 2: locate OSS anchors (strings / constant tables) in Serum2 Win64 and map them to referencing functions.
usage: sr3_anchors.py <pe> <index.npz> <anchors.json-out>
Anchors are declared in ANCHORS below: (lib, name, kind, bytes-pattern).  Every hit is reported with file RVA, section,
referencing function(s) (via the rip-relative index).  No hit => anchor listed with hits=0 (negative evidence is kept)."""
import sys, json, bisect, re, struct
import numpy as np
import pefile

PATH, IDX, OUT = sys.argv[1:4]
pe = pefile.PE(PATH, fast_load=True)
data = open(PATH, 'rb').read()
IMG = pe.OPTIONAL_HEADER.ImageBase
secs = [(s.Name.rstrip(b'\0').decode(), s.VirtualAddress, s.Misc_VirtualSize, s.PointerToRawData, s.SizeOfRawData) for s in pe.sections]
z = np.load(IDX)
funcs = z['funcs']; refs = z['refs']
fstarts = funcs[:, 0].tolist()
rip = refs[refs[:, 2] == 0]
rip_by_t = {}
order = np.argsort(rip[:, 1], kind='stable')
rip_sorted_t = rip[order, 1]; rip_sorted_s = rip[order, 0]


def fn_of(rva):
    i = bisect.bisect_right(fstarts, rva) - 1
    if i >= 0 and funcs[i][0] <= rva < funcs[i][1]:
        return int(funcs[i][0])
    return -1


def off2rva(off):
    for n, va, vs, po, ps in secs:
        if po <= off < po + ps:
            return n, va + off - po
    return None, None


def referers(rva, span=1):
    """functions with a rip-relative ref into [rva, rva+span)"""
    lo = np.searchsorted(rip_sorted_t, rva, 'left'); hi = np.searchsorted(rip_sorted_t, rva + span, 'left')
    return sorted({fn_of(int(s)) for s in rip_sorted_s[lo:hi]} - {-1})


A = []
def S(lib, name, s): A.append((lib, name, 'str', s if isinstance(s, bytes) else s.encode()))
def X(lib, name, hexs): A.append((lib, name, 'hex', bytes.fromhex(hexs.replace(' ', ''))))

# --- SQLite (strings that exist only in sqlite3.c; version string prefix = "3.")
S('sqlite', 'sqlite_source_id_prefix', '2025-'); S('sqlite', 'sqlite_source_id_prefix24', '2024-')
S('sqlite', 'fileheader', b'SQLite format 3\0')
S('sqlite', 'ver_fn', 'sqlite_version'); S('sqlite', 'src_id_fn', 'sqlite_source_id')
S('sqlite', 'sqlite_master', 'sqlite_master'); S('sqlite', 'sqlite_schema', 'sqlite_schema')
S('sqlite', 'cant_open', 'unable to open database file'); S('sqlite', 'corrupt', 'database disk image is malformed')
S('sqlite', 'keywords', 'REINDEXEDESCAPEACHECKEYBEFOREIGNOREGEXPLAINSTEADDATABASELECT')
S('sqlite', 'opnames', 'Savepoint'); S('sqlite', 'fts5', 'fts5'); S('sqlite', 'json_each', 'json_each')
S('sqlite', 'compile_opt', 'COMPILER=')
# --- nlohmann::json
S('nlohmann_json', 'rtti_abi', '.?AVjson_abi_v3_12_0'); S('nlohmann_json', 'abi_str', 'json_abi_v3_12_0')
S('nlohmann_json', 'parse_error', 'parse error'); S('nlohmann_json', 'type_error', 'type must be')
S('nlohmann_json', 'invalid_iter', 'cannot use operator[] with a string argument')
S('nlohmann_json', 'ver_3_12', '3.12.0')
# --- muParser
S('muparser', 'rtti_parser', '.?AVParser@mu@@'); S('muparser', 'rtti_base', '.?AVParserBase@mu@@')
S('muparser', 'rtti_err', '.?AVParserError@mu@@'); S('muparser', 'sin', 'sin'); S('muparser', 'sign', 'sign')
S('muparser', 'rnd', 'rnd'); S('muparser', 'msg_unexp', 'Unexpected token')
S('muparser', 'msg_unassigned', 'Unassigned token'); S('muparser', 'ver', '2.3.')
# --- libsfz
S('libsfz', 'rtti_sound', '.?AVSound@libsfz@@'); S('libsfz', 'generated', '// SFZ Generated by libSFZ')
S('libsfz', 'lokey', 'lokey'); S('libsfz', 'pitch_keycenter', 'pitch_keycenter')
# --- libsndfile / FLAC / Vorbis
S('libsndfile', 'invalid_fmt', 'Invalid file format'); S('libsndfile', 'riff', b'RF64'); S('libsndfile', 'caff', b'caff')
S('libsndfile', 'nist', b'NIST_1A'); S('libsndfile', 'snd', b'.snd'); S('libsndfile', 'ver_str', 'libsndfile-1.')
S('libsndfile', 'sf_err', 'File contains data in an unknown format')
S('flac', 'hdr_fail', 'Failed to decode FLAC header'); S('flac', 'fLaC', b'fLaC')
S('flac', 'ver', 'reference libFLAC'); S('flac', 'vendor', 'reference libFLAC 1.')
S('vorbis', 'vorbis', b'\x01vorbis'); S('vorbis', 'ogg', b'OggS'); S('vorbis', 'xiph', 'Xiph.Org libVorbis')
# --- PFFFT / ZL convolver
S('pffft', 'pffft', 'pffft'); S('pffft', 'ver_sse', 'PFFFT'); S('zita', 'zita', 'zita'); S('zita', 'zl', 'ZL')
S('zita', 'rtti_conv', '.?AVConvolver'); S('zita', 'rtti_zl', '.?AVZL')
# --- zlib: inflate/deflate constants (strings absent, use tables)
S('zlib', 'inflate_err_hdr', 'incorrect header check'); S('zlib', 'inflate_err_blk', 'invalid block type')
S('zlib', 'zlib_ver', 'deflate 1.'); S('zlib', 'zlib_ver2', 'inflate 1.'); S('zlib', 'zver', '1.3')
# zlib inflate fixed tables / crc32 / adler: crc32 poly table start (little endian)
X('zlib_or_crc', 'crc32_table_start', '00000000 96300777 2c610eee ba510999 19c46d07')
X('zlib_or_crc', 'crc32_table_start_be', '00000000 77073096 ee0e612c 990951ba')
X('zlib', 'inflate_lbase', '03 00 04 00 05 00 06 00 07 00 08 00 09 00 0a 00 0b 00 0d 00 0f 00 11 00 13 00 17 00 1b 00 1f 00')
X('zlib', 'inflate_dbase', '01 00 02 00 03 00 04 00 05 00 07 00 09 00 0d 00 11 00 19 00 21 00 31 00 41 00 61 00 81 00 c1 00')
X('zlib', 'deflate_base_length', '00 01 02 03 04 05 06 07 08 0a 0c 0e 10 14 18 1c 20 28 30 38 40 50 60 70 80 a0 c0 e0 00')
# --- zstd: version, FSE/Huffman default tables, magic, xxh64 primes, repcode
X('zstd', 'frame_magic', '28 b5 2f fd')
X('zstd', 'xxh64_prime1', '8b 7a 51 b1 b9 79 37 9e')
X('zstd', 'xxh64_prime2', '4f 4a 4b 8b 3d 77 ec c2')  # 0xC2B2AE3D27D4EB4F LE
X('zstd', 'LL_bits', '00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 01 01 01 01 02 02 03 03 04 06 07 08 09 0a 0b 0c 0d 0e 0f 10')
X('zstd', 'ML_bits', '00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 00 01 01 01 01 02 02 03 03 04 04 05 07 08 09 0a 0b 0c 0d 0e 0f 10')
S('zstd', 'err_prefix_unknown', 'Unknown frame descriptor'); S('zstd', 'ver_zstd', 'zstd')
# --- MTS-ESP client / VST3 SDK (for boundary, not for rebuild)
S('mts_esp', 'libmts', 'LIBMTS.dll'); S('mts_esp', 'mts_esp_dir', 'MTS-ESP')
S('vst3sdk', 'rtti_audioeffect', '.?AVAudioEffect@Vst@Steinberg@@'); S('vst3sdk', 'rtti_editctl', '.?AVEditController@Vst@Steinberg@@')
S('vstgui', 'rtti_cview', '.?AVCView@VSTGUI@@'); S('vstgui', 'rtti_cframe', '.?AVCFrame@VSTGUI@@')

res = []
for lib, name, kind, pat in A:
    hits = [m.start() for m in re.finditer(re.escape(pat), data)]
    ent = {'lib': lib, 'name': name, 'kind': kind, 'pattern': pat.decode('latin1') if kind == 'str' else pat.hex(), 'hits': []}
    for h in hits[:20]:
        sec, rva = off2rva(h)
        if rva is None:
            continue
        ent['hits'].append({'file_off': h, 'section': sec, 'rva': rva, 'va': IMG + rva,
                            'ref_funcs': [hex(IMG + f) for f in referers(rva, len(pat))][:12]})
    ent['n_hits_total'] = len(hits)
    res.append(ent)
json.dump(res, open(OUT, 'w'), indent=1)
for e in res:
    rf = sum(len(h['ref_funcs']) for h in e['hits'])
    print(f"{e['lib']:<14}{e['name']:<26}hits={e['n_hits_total']:<4} sec={','.join(sorted({h['section'] for h in e['hits']})):<10} ref_funcs={rf}")
