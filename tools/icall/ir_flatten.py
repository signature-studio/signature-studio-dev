#!/usr/bin/env python3
"""ir_flatten.py — RetDec IR (normalize 済み opaque-ptr 形) の @global_var_<va> を絶対アドレス定数へ展開し、VA を wasm32 へ shift する.
  python3 ir_flatten.py IN.ll OUT.ll --base 0x180000000 --newbase 0x30000000 --limit 0x4800000 [--table table.c]
  - `@global_var_<hex>` 定義行を削除 (データ実体は ott_data_install 相当が線形メモリへ敷設; D2 小さすぎる global の根絶)
  - 参照を `inttoptr (i64 <shifted> to ptr)` へ置換
  - i64 定数 (base..base+limit) を shift
  - `--table`: 0 引数 define の VA→関数 表 (icall dispatch 用) を C で出力
"""
import argparse, re


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src'); ap.add_argument('dst')
    ap.add_argument('--base', type=lambda x: int(x, 0), default=0x180000000)
    ap.add_argument('--newbase', type=lambda x: int(x, 0), default=0x30000000)
    ap.add_argument('--limit', type=lambda x: int(x, 0), default=0x4800000)
    ap.add_argument('--table')
    ap.add_argument('--cfg', default='', help='CFG thunk の原 VA (hex, comma)')
    a = ap.parse_args()
    shift = a.base - a.newbase
    text = open(a.src, errors='replace').read()
    lines = text.split('\n')
    out = []
    ndef = 0
    seen_decl = set()
    for l in lines:
        if l.startswith('declare '):
            mm = re.search(r'@([\w.$"-]+)\(', l)
            if mm:
                if mm.group(1) in seen_decl:
                    continue
                seen_decl.add(mm.group(1))
        if l.startswith('@global_var_') and ' = ' in l:
            ndef += 1
            continue
        out.append(l)
    text = '\n'.join(out)

    def sh(v):
        return v - shift if a.base <= v < a.base + a.limit else v

    def gsub(m):
        v = int(m.group(1), 16)
        return 'inttoptr (i64 %d to ptr)' % sh(v)
    text, ng = re.subn(r'@global_var_([0-9a-f]+)\b', gsub, text)
    nc = [0]

    def csub(m):
        v = int(m.group(1))
        nv = sh(v)
        if nv != v:
            nc[0] += 1
        return str(nv)
    # 整数リテラル (i64 直後だけでなく `add i64 %x, 6443633844` のような 2 項目も) を対象。float/hex/識別子/メタデータ内は除外
    text = re.sub(r'(?<![\w.%@!\-+])(\d{10,11})(?![\w.])', csub, text)
    text, nfix = re.subn(r'(= (?:add|sub|mul|and|or|xor) i64 [^,\n]+, )i64 (%|-?\d)', r'\1\2', text)   # ir5_patch A9 の `add i64 0, i64 %x` 形崩れ
    open(a.dst, 'w').write(text)
    print('[flatten] A9 malformed binop fixed', nfix)
    print('[flatten] global defs removed %d, refs %d, i64 consts shifted %d' % (ndef, ng, nc[0]))
    if a.table:
        CT = {'i64': 'long long', 'i128': 'unsigned __int128', 'i32': 'int', 'i16': 'short', 'i8': 'signed char', 'i1': 'int', 'void': 'void', 'ptr': 'void*', 'double': 'double', 'float': 'float'}
        INTREG = [0x08, 0x10, 0x18, 0x20]   # BLK: rcx, rdx, r8, r9 (icall_rewrite.py)
        defs = {}
        for m in re.finditer(r'^define (\S+) @function_([0-9a-f]+)\(([^)]*)\)', text, re.M):
            ps = [p.split()[0] for p in m.group(3).split(',') if p.strip()]
            defs[int(m.group(2), 16)] = (m.group(1), ps)
        o = ['/* generated by ir_flatten.py: VA(shifted) -> lifted function table (戻り型・引数が違う関数は wrapper で long long(void) に揃える。引数は BLK から読む) */',
             '#include <stdint.h>', '#include <stddef.h>', '#include <string.h>',
             '#ifdef ICALL_BLK_GLOBAL', 'extern unsigned char __icall_blk[0x200];', '#define BLK_ADDR ((uintptr_t)__icall_blk)', '#else',
             '#ifndef ICALL_BLK', '#define ICALL_BLK 0x34308000u', '#endif', '#define BLK_ADDR ((uintptr_t)ICALL_BLK)', '#endif',
             '#define BLKQ(off) (*(volatile uint64_t*)(BLK_ADDR + (off)))',
             'static double bd_(uint64_t u){ double d; memcpy(&d, &u, 8); return d; }',
             'static float bf_(uint64_t u){ float f; uint32_t w = (uint32_t)u; memcpy(&f, &w, 4); return f; }']
        names = []
        skipped = []
        for d in sorted(defs):
            rtype, ps = defs[d]
            rt = CT.get(rtype, 'long long')
            if rtype not in CT or any(p not in CT or p in ('void', 'i128') for p in ps):
                skipped.append(d)
                continue
            if not ps:
                o.append('extern %s function_%x(void);' % (rt, d))
                if rt == 'long long':
                    names.append('function_%x' % d)
                else:
                    o.append('static long long w_%x(void){ %sfunction_%x(); return 0; }' % (d, '' if rt == 'void' else '(void)', d))
                    names.append('w_%x' % d)
                continue
            args = []
            for k, p in enumerate(ps):
                if k < 4 and p in ('double', 'float'):
                    off = 0x28 + 8 * k
                elif k < 4:
                    off = INTREG[k]
                else:
                    off = 0x100 + 8 * (k - 4)
                if p == 'double':
                    args.append('bd_(BLKQ(0x%x))' % off)
                elif p == 'float':
                    args.append('bf_(BLKQ(0x%x))' % off)
                elif p == 'ptr':
                    args.append('(void*)(uintptr_t)BLKQ(0x%x)' % off)
                else:
                    args.append('(%s)BLKQ(0x%x)' % (CT[p], off))
            o.append('extern %s function_%x(%s);' % (rt, d, ', '.join(CT[p] for p in ps)))
            call = 'function_%x(%s)' % (d, ', '.join(args))
            body = call + ';' if rt == 'void' else '(void)' + call + ';'
            o.append('static long long w_%x(void){ %s return 0; }' % (d, body))
            names.append('w_%x' % d)
        ents = [d for d in sorted(defs) if d not in skipped]
        o.append('const uint32_t icall_tbl_va[] = {' + ','.join('0x%xu' % sh(d) for d in ents) + '};')
        o.append('long long (*const icall_tbl_fn[])(void) = {' + ','.join(names) + '};')
        o.append('const unsigned icall_tbl_n = %d;' % len(ents))
        cf = [int(x, 16) for x in a.cfg.split(',') if x]
        o.append('const uint32_t icall_cfg_va[] = {' + ','.join('0x%xu' % sh(d) for d in cf) + (',' if cf else '') + '0};')
        o.append('const unsigned icall_cfg_n = %d;' % len(cf))
        open(a.table, 'w').write('\n'.join(o) + '\n')
        print('[flatten] table entries %d (skipped %d; with args or non-i64 ret wrapped: %d)' % (len(ents), len(skipped), sum(1 for d in ents if defs[d][0] != 'i64' or defs[d][1])))


if __name__ == '__main__':
    main()
