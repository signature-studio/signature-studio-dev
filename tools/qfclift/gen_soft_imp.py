#!/usr/bin/env python3
"""gen_soft_imp.py <lift_meta.json> <rt dir> <out.c> [impl.c ...] — QuickFontCache の import のうち rt (fle_cpu.c / fle_glue.c)
と impl.c (qfc_imp.c) に実装が無い名前に、呼出しを stderr へ記録して 0 を返す soft stub を生成する (T-SH-60 / #3289 の boot 測定専用)。
soft stub の戻り値は実物ではない。boot の結果を PASS の根拠にしない (qfc_boot.sh の注記参照)。"""
import json, re, sys

meta, rt, out = sys.argv[1], sys.argv[2], sys.argv[3]
impl = set()
for f in [f'{rt}/fle_cpu.c', f'{rt}/fle_glue.c', *sys.argv[4:]]:   # 末尾の引数 = qfc_imp.c (実装済みの名前)
    impl |= set(re.findall(r'void imp_(\w+)\(void\)', open(f).read()))
used = set(json.load(open(meta))['imports_used'])
names = sorted(used - impl)
with open(out, 'w') as fh:
    fh.write('/* generated by gen_soft_imp.py (T-SH-60 boot 測定用 soft stub。呼出しを記録して 0 を返す) */\n')
    fh.write('#include <stdio.h>\n#include "fle_cpu.h"\n')
    for nm in names:
        fh.write('void imp_%s(void) { fprintf(stderr, "[qfc-soft] %s\\n"); R[RAX] = 0; R[RSP] += 8; }\n' % (nm, nm))
print('[gen_soft_imp] imports used %d / rt 実装済み %d / soft stub %d' % (len(used), len(used & impl), len(names)))
