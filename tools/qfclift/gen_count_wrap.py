#!/usr/bin/env python3
"""gen_count_wrap.py <lift_meta.json> <fle_lifted.c> <out_dir> — T-SH-78 / #3411 の import 呼出し計数専用の測定版を作る。
  out_dir/fle_lifted.c : 入力の直接呼出し `imp_<名前>();` (lift 済み import のみ) を `__cnt_imp_<名前>();` に書き換えた複製。
                         加えて imp_tab (IAT 順の間接呼出し表) の各行を `__cnt_ind_<k>` に書き換える (T-SH-121 / #4374)。
  out_dir/count_wrap.c : `__cnt_imp_<名前>` (stderr に "[fle] CALL <名前>" を 1 行出し、元の imp_<名前>() を呼ぶ)
                         `__cnt_ind_<k>` (stderr に "[fle] CALL <名前> (ind)" を 1 行出し、元の行き先を呼ぶ。
                         行き先が imp_unimpl のときは元と同じく ott_missing_import("(unresolved import)") を呼ぶ)
--wrap は同一 TU の weak 定義への呼出しに効かないため使わない。戻り値・副作用は元の imp_<名前> に任せる (計数だけ追加)。
imp_by_index → imp_tab[k]() の経路は行き先を変えない (k 行目の関数を呼ぶだけ)。"""
import json, os, re, sys

meta, src, out = sys.argv[1], sys.argv[2], sys.argv[3]
M = json.load(open(meta))
names = set(M['imports_used'])
ind_names = [None] * len(M['iat_map'])
for v in M['iat_map'].values():
    ind_names[v['index']] = v['name']
os.makedirs(out, exist_ok=True)
hits = {}
def rep(m):
    nm = m.group(1)
    if nm in names:
        hits[nm] = hits.get(nm, 0) + 1
        return '__cnt_imp_%s();' % nm
    return m.group(0)

txt = open(src).read()
tab = re.search(r'static void \(\*const imp_tab\[\]\)\(void\) = \{\n(.*?)\n\};', txt, re.S)
rows = [r.strip().rstrip(',') for r in tab.group(1).split('\n')]
assert len(rows) == len(ind_names), (len(rows), len(ind_names))
ind_hits = {}
new_rows = []
for k, r in enumerate(rows):
    new_rows.append('  __cnt_ind_%d' % k)
    if r == 'imp_unimpl':
        ind_hits[k] = None
    else:
        assert r == 'imp_' + ind_names[k], (k, r, ind_names[k])
        ind_hits[k] = ind_names[k]
txt = txt[:tab.start(1)] + ',\n'.join(new_rows) + txt[tab.end(1):]
txt = re.sub(r'\bimp_(\w+)\(\);', rep, txt)

decl = ''.join('void __cnt_imp_%s(void);\n' % nm for nm in sorted(hits))
decl += ''.join('void __cnt_ind_%d(void);\n' % k for k in range(len(rows)))
open(os.path.join(out, 'fle_lifted.c'), 'w').write(decl + txt)
with open(os.path.join(out, 'count_wrap.c'), 'w') as fh:
    fh.write('/* generated by gen_count_wrap.py (T-SH-78 / #3411 ・ T-SH-121 / #4374 の呼出し計数専用。戻り値は変えない) */\n')
    fh.write('#include <stdio.h>\n')
    fh.write('extern void ott_missing_import(const char*);\n')
    for nm in sorted(hits):
        fh.write('extern void imp_%s(void);\n' % nm)
        fh.write('void __cnt_imp_%s(void) { fprintf(stderr, "[fle] CALL %s\\n"); imp_%s(); }\n' % (nm, nm, nm))
    for k in range(len(rows)):
        nm = ind_hits[k]
        if nm is None:
            fh.write('void __cnt_ind_%d(void) { fprintf(stderr, "[fle] CALL %s (ind)\\n"); ott_missing_import("(unresolved import)"); }\n' % (k, ind_names[k]))
        else:
            fh.write('extern void imp_%s(void);\n' % nm)
            fh.write('void __cnt_ind_%d(void) { fprintf(stderr, "[fle] CALL %s (ind)\\n"); imp_%s(); }\n' % (k, nm, nm))
print('[gen_count_wrap] import used %d / 書換えた直接呼出し箇所 %d (名前別 %d 種) / imp_tab 行 %d (used %d)' % (
    len(names), sum(hits.values()), len(hits), len(rows), sum(1 for v in ind_hits.values() if v)))
