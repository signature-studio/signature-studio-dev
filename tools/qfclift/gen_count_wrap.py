#!/usr/bin/env python3
"""gen_count_wrap.py <lift_meta.json> <fle_lifted.c> <out_dir> — T-SH-78 / #3411 の import 呼出し計数専用の測定版を作る。
  out_dir/fle_lifted.c : 入力の直接呼出し `imp_<名前>();` (lift 済み import のみ) を `__cnt_imp_<名前>();` に書き換えた複製
  out_dir/count_wrap.c : `__cnt_imp_<名前>` (stderr に "[fle] CALL <名前>" を 1 行出し、元の imp_<名前>() を呼ぶ)
--wrap は同一 TU の weak 定義への呼出しに効かないため使わない。戻り値・副作用は元の imp_<名前> に任せる (計数だけ追加)。
関数表 (imp_tab) 経由の間接呼出しは書き換えない (計数に入らない。REPORT に明記する)。"""
import json, os, re, sys

meta, src, out = sys.argv[1], sys.argv[2], sys.argv[3]
names = set(json.load(open(meta))['imports_used'])
os.makedirs(out, exist_ok=True)
hits = {}
def rep(m):
    nm = m.group(1)
    if nm in names:
        hits[nm] = hits.get(nm, 0) + 1
        return '__cnt_imp_%s();' % nm
    return m.group(0)
txt = re.sub(r'\bimp_(\w+)\(\);', rep, open(src).read())
decl = ''.join('void __cnt_imp_%s(void);\n' % nm for nm in sorted(hits))
open(os.path.join(out, 'fle_lifted.c'), 'w').write(decl + txt)
with open(os.path.join(out, 'count_wrap.c'), 'w') as fh:
    fh.write('/* generated by gen_count_wrap.py (T-SH-78 / #3411 の呼出し計数専用。戻り値は変えない) */\n')
    fh.write('#include <stdio.h>\n')
    for nm in sorted(hits):
        fh.write('extern void imp_%s(void);\n' % nm)
        fh.write('void __cnt_imp_%s(void) { fprintf(stderr, "[fle] CALL %s\\n"); imp_%s(); }\n' % (nm, nm, nm))
print('[gen_count_wrap] import used %d / 書換えた直接呼出し箇所 %d (名前別 %d 種)' % (len(names), sum(hits.values()), len(hits)))
